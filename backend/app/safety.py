"""Conservative routing for obvious hazards, not a medical triage classifier."""

import re


def safety_response(message: str) -> str | None:
    text = message.lower().replace("ё", "е")
    # Explicit emergency descriptions take precedence over retrieval and generation.
    dangerous = (
        r"теряю сознание|потеряла сознание|падаю в обморок|не могу дышать",
        r"(?:резкая|невыносимая|внезапная|очень сильная).{0,25}бол[ьи].{0,30}(?:живот|таз)",
        r"(?:прокладк|тампон).{0,45}(?:каждые? полчаса|за полчаса|за 30 минут)",
        r"(?:кровотеч|кровь|месячн).{0,80}(?:обморок|сильн.{0,8}головокруж|не могу встать)",
        r"хочу (?:умереть|убить себя)|покончить с собой",
    )
    if any(re.search(pattern, text) for pattern in dangerous):
        return (
            "Если это происходит сейчас, нужна срочная помощь. В России позвоните 112 или 103 "
            "и опишите симптомы диспетчеру; в другой стране — по местному экстренному номеру. "
            "По возможности попросите человека рядом остаться с вами. Не ждите ответа чата. "
            "По переписке нельзя установить причину или исключить опасное состояние."
        )
    medication = r"(?:какую|какой|сколько|подбери|назначь).{0,30}(?:доз|таблет|препарат|лекарств|мг|гормон)|(?:отменить|отмени|перестать пить|увеличить доз|снизить доз)|чем лечить|схем.{0,10}лечени"
    if re.search(medication, text):
        return (
            "Я могу объяснить общие понятия, но не подбираю лекарства, дозировки и схемы лечения. "
            "Не меняйте назначение самостоятельно: уточните его у лечащего врача или фармацевта. "
            "Для разговора подготовьте название препарата, назначенную схему и описание изменений самочувствия."
        )
    return None
