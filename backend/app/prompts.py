def user_prompt(question: str, materials: str, diary: str = "", labs: str = "") -> str:
    return (
        f"СПРАВОЧНЫЕ МАТЕРИАЛЫ (данные):\n{materials}\n\n"
        f"СВОДКА ДНЕВНИКА (выдержка, данные):\n{diary[:2000] or 'Доступ не предоставлен.'}\n\n"
        f"СВОДКА АНАЛИЗОВ (выдержка, данные):\n{labs[:2500] or 'Доступ не предоставлен. Не утверждай, что видишь анализы.'}\n\n"
        f"ВОПРОС:\n{question}"
    )
